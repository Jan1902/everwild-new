"""Computes the rumble of the Rift and writes it to assets/sounds/quake.wav.

    python tools/quake_sound.py

The sound is made from filtered noise, not generated by a model, so it costs nothing and comes out
the same every time. It swells for as long as the screen shakes and then dies away in the dark;
the times match QUAKE_DURATION and QUAKE_DARK in src/view/game.gd.
"""

import math
import random
import struct
import wave
from pathlib import Path

RATE = 22050
SWELL = 2.8
DECAY = 2.2
OUTPUT = Path(__file__).resolve().parent.parent / "assets" / "sounds" / "quake.wav"


def low_pass(samples: list[float], cutoff: float) -> list[float]:
    """Two one-pole filters in a row."""
    weight = 1.0 - math.exp(-2.0 * math.pi * cutoff / RATE)
    for _ in range(2):
        value = 0.0
        filtered = []
        for sample in samples:
            value += weight * (sample - value)
            filtered.append(value)
        samples = filtered
    return samples


def normalised(samples: list[float]) -> list[float]:
    peak = max(abs(sample) for sample in samples)
    return [sample / peak for sample in samples]


def main() -> None:
    noise = random.Random(7)
    count = int((SWELL + DECAY) * RATE)
    white = [noise.uniform(-1.0, 1.0) for _ in range(count)]
    # The deep part is what headphones carry; the higher part is what a phone speaker can play.
    deep = normalised(low_pass(white, 90.0))
    body = normalised(low_pass(white, 420.0))
    # Slow, irregular heaving, so it does not sound like a steady hum.
    heave = normalised(low_pass([noise.uniform(-1.0, 1.0) for _ in range(count)], 5.0))

    samples = []
    for number in range(count):
        time = number / RATE
        if time < SWELL:
            loudness = (time / SWELL) ** 2
        else:
            loudness = math.exp(-(time - SWELL) * 3.0 / DECAY) * (1.0 - (time - SWELL) / DECAY)
        samples.append((0.65 * deep[number] + 0.35 * body[number]) * (0.7 + 0.3 * heave[number]) * loudness)
    samples = normalised(samples)

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    with wave.open(str(OUTPUT), "wb") as file:
        file.setnchannels(1)
        file.setsampwidth(2)
        file.setframerate(RATE)
        file.writeframes(b"".join(struct.pack("<h", int(sample * 0.85 * 32767)) for sample in samples))
    print(f"written {OUTPUT.name}: {count / RATE:.1f} s")


if __name__ == "__main__":
    main()
