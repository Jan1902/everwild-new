"""Computes the small sounds of the game and writes them to assets/sounds/.

    python tools/sound_effects.py

Like the rumble of the Rift (quake_sound.py) everything here is made from sine waves, noise and
simple filters, not generated by a model: it costs nothing, needs no packages and comes out the
same every time.

  kindle.wav             a flame catching
  insight.wav            two thoughts that fit together in the notebook
  miss.wav               two thoughts that do not
  whole.wav              a piece of the world becoming whole
  page.wav               the notebook opening
  music_box.wav          the melody of the old man's music box, a seamless loop

The voices of the figures were computed here as well, as sung syllables. They sounded like robots
(Jan, 2026-10-14); they are generated now (tools/voice_sounds.py).
"""

import math
import random
import struct
import wave
from pathlib import Path

RATE = 22050
OUTPUT = Path(__file__).resolve().parent.parent / "assets" / "sounds"


# The music box: three bars of 3/4 a line, a quarter note this many seconds.
BEAT = 0.62
# MIDI note and length in beats. D major, eight bars.
MELODY = [
    (69, 1), (74, 1), (78, 1),
    (76, 2), (74, 1),
    (71, 1), (74, 1), (79, 1),
    (78, 3),
    (81, 1), (79, 1), (78, 1),
    (76, 1), (78, 1), (81, 1),
    (79, 1), (76, 1), (73, 1),
    (74, 3),
]
# One deep note at the start of every bar.
BASS = [50, 57, 55, 50, 50, 57, 57, 50]


def write(name: str, samples: list[float], volume: float = 0.85) -> None:
    peak = max(abs(sample) for sample in samples) or 1.0
    target = OUTPUT / name
    target.parent.mkdir(parents=True, exist_ok=True)
    with wave.open(str(target), "wb") as file:
        file.setnchannels(1)
        file.setsampwidth(2)
        file.setframerate(RATE)
        file.writeframes(b"".join(struct.pack("<h", int(sample / peak * volume * 32767)) for sample in samples))


def low_pass(samples: list[float], cutoff: float) -> list[float]:
    weight = 1.0 - math.exp(-2.0 * math.pi * cutoff / RATE)
    value, out = 0.0, []
    for sample in samples:
        value += weight * (sample - value)
        out.append(value)
    return out


def kindle() -> None:
    chance = random.Random(3)
    count = int(0.9 * RATE)
    noise = [chance.uniform(-1, 1) for _ in range(count)]
    whoosh = low_pass(noise, 900)
    samples = []
    for number in range(count):
        time = number / RATE
        swell = min(1.0, time / 0.12) * math.exp(-max(0.0, time - 0.12) * 4.0)
        # A few crackles, like a wick taking the flame.
        crackle = noise[number] * 0.8 if chance.random() < 0.0016 * math.exp(-time * 3) else 0.0
        samples.append(whoosh[number] * swell * 2.5 + crackle)
    write("kindle.wav", low_pass(samples, 5000), 0.6)


def bell(frequency: float, time: float, decay: float = 1.6) -> float:
    """A soft bell: a few partials that fade at different speeds."""
    value = 0.0
    for ratio, weight, speed in [(1.0, 1.0, 1.0), (2.0, 0.35, 1.8), (3.01, 0.15, 2.6), (4.2, 0.08, 3.5)]:
        value += weight * math.sin(2.0 * math.pi * frequency * ratio * time) * math.exp(-time * speed / decay)
    return value * min(1.0, time / 0.004)


def tones(notes: list[tuple[float, float]], length: float, decay: float = 1.6) -> list[float]:
    """Bell notes (start in seconds, MIDI note) over the given number of seconds."""
    count = int(length * RATE)
    samples = [0.0] * count
    for start, note in notes:
        frequency = 440.0 * 2 ** ((note - 69) / 12)
        for number in range(int(start * RATE), count):
            samples[number] += bell(frequency, number / RATE - start, decay)
    return samples


def insight() -> None:
    write("insight.wav", tones([(0.0, 79), (0.14, 86), (0.28, 91)], 2.2, 1.4), 0.55)


def miss() -> None:
    write("miss.wav", tones([(0.0, 64), (0.09, 63)], 0.7, 0.4), 0.3)


def whole() -> None:
    # A slow chord that opens upwards, with a shimmer of noise.
    chance = random.Random(5)
    notes = [(0.0, 62), (0.18, 66), (0.36, 69), (0.54, 74), (0.9, 78), (1.1, 81)]
    samples = tones(notes, 4.5, 3.0)
    air = low_pass([chance.uniform(-1, 1) for _ in samples], 3000)
    for number in range(len(samples)):
        time = number / RATE
        samples[number] += air[number] * 0.25 * math.sin(math.pi * min(1.0, time / 4.5))
    write("whole.wav", samples, 0.6)


def page() -> None:
    chance = random.Random(9)
    count = int(0.35 * RATE)
    noise = [chance.uniform(-1, 1) for _ in range(count)]
    rustle = low_pass(noise, 2500)
    samples = []
    for number in range(count):
        time = number / RATE
        samples.append(rustle[number] * math.sin(math.pi * min(1.0, time / 0.35)) ** 2 * (1.0 + 0.6 * math.sin(time * 90)))
    write("page.wav", samples, 0.35)


def music_box() -> None:
    """The melody on a music box: bright, plucked notes that ring on. The end flows into the
    beginning, so it can loop without a seam."""
    length = sum(beats for _, beats in MELODY) * BEAT
    count = int(length * RATE)
    samples = [0.0] * count
    tail = int(2.5 * RATE)

    def pluck(start: float, note: int, loudness: float) -> None:
        frequency = 440.0 * 2 ** ((note - 69) / 12)
        first = int(start * RATE)
        for offset in range(tail):
            time = offset / RATE
            # A tine of a music box: a pure tone, a faint octave and a quick metallic shimmer.
            value = math.sin(2 * math.pi * frequency * time) * math.exp(-time * 1.6)
            value += 0.3 * math.sin(2 * math.pi * frequency * 2.0 * time) * math.exp(-time * 3.0)
            value += 0.12 * math.sin(2 * math.pi * frequency * 5.4 * time) * math.exp(-time * 14.0)
            samples[(first + offset) % count] += value * loudness * min(1.0, time / 0.002)

    beat = 0.0
    for note, beats in MELODY:
        pluck(beat * BEAT, note, 1.0)
        beat += beats
    for bar, note in enumerate(BASS):
        pluck(bar * 3 * BEAT, note, 0.45)
        pluck((bar * 3 + 1.5) * BEAT, note + 12, 0.18)
    write("music_box.wav", samples, 0.7)


def main() -> None:
    kindle()
    insight()
    miss()
    whole()
    page()
    music_box()
    print("written to", OUTPUT)


if __name__ == "__main__":
    main()
